#!/usr/bin/env bash
# Journey: a direct summary refresh of a home at fleet scale publishes well inside its deadline.
# The fixture has the shape of a busy home: 6,400 backlog rows with about three body lines each
# (some 26,000 lines of backlog markdown), PR links on the closed rows, 300 captain holds whose
# reasons carry parentheses and commas (so the view encodes them), and 600 saved contribution
# records. The real producer runs, with no stand-in.
# A direct `jg-home-summary-refresh.sh` must exit 0 in under 20 seconds, a third of its 60-second
# deadline (it takes about 8 seconds here; it took over 30 before the backlog parse, the
# hold-reason decode and the saved-contribution read were made linear), publish a ledger
# generated after the call began, render state/whats-left.md, and carry each hold reason decoded.
set -u
# shellcheck source=tests/lib.sh
# shellcheck disable=SC1091
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

command -v jq >/dev/null 2>&1 || { echo "skip: jq not found"; exit 0; }
[ -z "${DONE_DONE_EVIDENCE_ROOT:-}" ] || exec > >(tee "$DONE_DONE_EVIDENCE_ROOT/home-summary-refresh-scale.log")

T=$(jg_test_tmproot jg-home-summary-scale)
H=$T/home
mkdir -p "$H/config" "$H/data" "$H/state" "$H/projects" "$H/fakebin"
jg_fake_exit0 "$H/fakebin" tmux treehouse no-mistakes gh gh-axi
printf -- '- demo [local-trunk] - the registered project (added 2026-11-01)\n' > "$H/data/projects.md"
REASON='waits (for the owner), then ships'

python3 - "$T/rows.jsonl" "$H/data" "$REASON" <<'PY'
import json, os, sys
rows_path, data, reason = sys.argv[1:4]
line = "Notes from the lane: the change was proven on the fixture home, reviewed, and landed on the trunk with its checks green. "
with open(rows_path, "w") as out:
    for i in range(1, 6401):
        row = {"id": "jg-row-%d" % i, "title": "[feature] Fleet row %d keeps its board tidy (step %d of the plan)" % (i, i % 7),
               "status": "closed", "priority": i % 4, "issue_type": "task", "created_at": "2026-10-01T00:00:00Z",
               "closed_at": "2026-11-%02dT00:00:00Z" % (1 + i % 20), "labels": ["project:demo"], "metadata": {},
               "description": "\n".join([line, line + "parent: upkeep", "Captain %d: keep it small." % i])}
        if i % 10 == 0:
            row["external_ref"] = "https://github.com/demo-org/demo/pull/%d" % i
        if i > 5600:
            row.update(status="open", closed_at=None)
            if i % 8 == 0:
                row["dependencies"] = [{"issue_id": row["id"], "depends_on_id": "jg-row-%d" % (i - 1), "type": "blocks"}]
        if 6100 < i:
            row.update(status="on_hold", created_at="2026-11-10T00:00:00Z", metadata={"hold_reason": "%s, row %d" % (reason, i), "hold_kind": "captain"})
        out.write(json.dumps(row) + "\n")
check = {"name": "CI required", "id": 1, "status": "completed", "conclusion": "success", "started_at": "2026-11-01T00:00:00Z"}
for i in range(1, 601):
    task = "jg-row-%d" % (i * 10)
    os.makedirs(os.path.join(data, task), exist_ok=True)
    record = {"url": "https://github.com/demo-org/demo/pull/%d" % (i * 10), "kind": "pr", "checked_at": "2026-11-01T00:00:00Z",
              "error": None, "pending": [], "seen": [], "notified": [],
              "observation": {"head": "a" * 40, "state": "merged", "draft": False, "mergeable": "unknown", "can_merge": True,
                              "review_decision": "", "reviews": [], "events": [], "checks": [check] * 8}}
    with open(os.path.join(data, task, "contributions.json"), "w") as f:
        json.dump({"schema": "jg-contributions.v1", "task": task, "records": [record]}, f)
PY
JG_HOME="$H" python3 "$ROOT/core/item-store/adapters/tickets.py" import --home main "$T/rows.jsonl" >/dev/null \
  || fail "could not import the fixture rows"
lines=$(cd "$H" && JG_HOME="$H" bash -c '. "$1/bin/jg-backlog-lib.sh"; jg_backlog_text "$2/config"' _ "$ROOT" "$H" | wc -l)
[ "$lines" -ge 25000 ] || fail "the fixture backlog renders $lines markdown lines, not a busy home's 25,000 or more"

start=$(date +%s)
start_ms=$(date +%s%3N)
out=$(env PATH="$H/fakebin:$PATH" JG_HOME="$H" "$ROOT/bin/jg-home-summary-refresh.sh" 2>&1) \
  || fail "the direct refresh failed: $out"
took=$(( $(date +%s%3N) - start_ms ))
[ -z "${DONE_DONE_EVIDENCE_ROOT:-}" ] || printf 'direct refresh over %s backlog lines: %s ms\n' "$lines" "$took" \
  > "$DONE_DONE_EVIDENCE_ROOT/home-summary-refresh-scale.txt"
[ "$took" -lt 20000 ] || fail "the direct refresh over $lines backlog lines took $took ms, not under 20000 (a third of its deadline)"

LEDGER=$H/state/home-summary.json
jq -e --argjson start "$start" '.generated_epoch >= $start' "$LEDGER" >/dev/null \
  || fail "the ledger was not generated by this refresh"
[ -s "$H/state/whats-left.md" ] || fail "the refresh did not render state/whats-left.md"
held=$(jq -r --arg reason "$REASON" '[.queued[] | select(.hold_reason != null)] as $held
  | if ($held | length) > 0 and all($held[]; .hold_reason | startswith($reason)) then $held | length else 0 end' "$LEDGER")
[ "$held" -gt 0 ] || fail "the ledger's queued holds do not carry their decoded reasons: $(jq -c '[.queued[].hold_reason]' "$LEDGER")"
pass "a direct refresh over $lines backlog lines publishes in $took ms, renders what is left, and decodes $held listed hold reasons"
