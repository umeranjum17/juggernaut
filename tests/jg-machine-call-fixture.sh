#!/usr/bin/env bash
# Shared fixture for the captain-call machine suites tests/jg-machine-call.test.sh, tests/jg-machine-call-b.test.sh and
# tests/jg-machine-call-c.test.sh: a throwaway home with a real Beads store (no fleet record is copied), the bin/jg-machine.sh
# and bin/jg-captain-hold.sh helpers, and seed_call, which makes each sample call a suite needs through the real CLIs.
# A captain call's state is read through the existing jg-captain-hold.sh predicates. It is sourced, never run.
set -u
export JG_TASK_PRIORITY_CHECK=/nonexistent
# shellcheck source=tests/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

command -v jq >/dev/null 2>&1 || { echo "skip: jq not found"; exit 0; }
JM="$ROOT/bin/jg-machine.sh"
T=$(jg_test_tmproot jg-machine-call)
HOME_DIR="$T/home"
mkdir -p "$HOME_DIR/data" "$HOME_DIR/state" "$HOME_DIR/config" "$HOME_DIR/projects"
jg_test_beads_home "$HOME_DIR"
: > "$HOME_DIR/config/backlog-intake-loose"
FB=$(jg_fakebin "$HOME_DIR"); jg_fake_exit0 "$FB" tmux treehouse no-mistakes gh gh-axi

export PATH="$FB:$PATH" JG_HOME="$HOME_DIR" JG_STATE_OVERRIDE="$HOME_DIR/state" \
  JG_DATA_OVERRIDE="$HOME_DIR/data" JG_CONFIG_OVERRIDE="$HOME_DIR/config"
unset JG_MACHINES_TABLES
hold() { "$ROOT/bin/jg-captain-hold.sh" "$@"; }
# shellcheck disable=SC2034 # OUT and RC are read by the suites that source this file
jm() { OUT=$(bash "$JM" "$@" 2>&1); RC=$?; }
state_of() { jm show captain-call "$1"; printf '%s\n' "$OUT" | awk -F'\t' '$1=="state"{print $2}'; }
diverged_ids() { hold diverged | cut -f1 | LC_ALL=C sort; }
status_line() { printf '%s\n' "$2" >> "$HOME_DIR/state/$1.status"; }
reason="the captain must choose the sample option"
printf 'Use the first sample option.\n' > "$T/answer.txt"

# seed_call <state> <id>: one captain call about a made-up sample, in that state; the ids are generated by the suites.
seed_call() {
  case $1 in
    none) jg_test_backlog "$HOME_DIR" add "$2" "Ordinary sample work" --kind ship --repo sample >/dev/null || fail "seed plain $2" ;;
    open) hold hold "$2" --title "Choose the sample option for $2" --reason "$reason" --repo sample >/dev/null || fail "seed hold $2" ;;
    answered)
      seed_call open "$2"
      hold answer "$2" --decision-file "$T/answer.txt" --release >/dev/null || fail "seed answer $2"
      ;;
    diverged)
      seed_call open "$2"
      status_line sm8-origin "needs-decision [key=$2]: choose the sample option"
      status_line sm8-origin "resolved [key=$2]: answered: first option"
      ;;
    *) fail "seed_call: unknown state $1" ;;
  esac
}
