#!/usr/bin/env bash
# Behavior test for docs/state-machines.md (SM4): the one page where a fix lane finds a machine's table, command and example.
# The page's machine table is generated from core/machines/tables/*.tsv by render_index below.
# Regenerate the committed page with: bash tests/jg-machine-index.test.sh --write
# The generator is proved on tables seeded here; no fleet record is copied. Drift of the committed page
# against the real tables is report-only (it prints the command that fixes it and does not fail).
set -u
# shellcheck source=tests/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

DOC="$ROOT/docs/state-machines.md"
TABLES=${JG_MACHINES_TABLES:-$ROOT/core/machines/tables}
BEGIN='<!-- machines:begin (generated by tests/jg-machine-index.test.sh --write; do not edit) -->'
END='<!-- machines:end -->'

render_index() {  # <tables dir>: the generated block, one row per machine table
  local f rows
  rows=$(for f in "$1"/*.tsv; do
    [ -e "$f" ] || continue
    case $f in */known-baseline.tsv) continue ;; esac
    LC_ALL=C awk -F'\t' -v file="$(basename "$f" .tsv)" '
      $1 == "machine" { n = $2; c = $3; o = $4 }
      $1 == "state" { s++ }
      $1 == "edge" { e++ }
      END {
        if (n == "") n = file
        gsub(/\|/, "\\|", c); gsub(/\|/, "\\|", o)
        printf "| `%s` | `%s` | `%s` | %d | %d | `bin/jg-machine.sh next %s <id>` |\n", n, c, o, s, e, n
      }' "$f"
  done | LC_ALL=C sort)
  if [ -z "$rows" ]; then
    echo "No machine table is installed yet."
    return 0
  fi
  printf '%s\n%s\n%s\n' "| Machine | Record it holds | Owner | States | Edges | Ask |" "| --- | --- | --- | ---: | ---: | --- |" "$rows"
}

splice() {  # <doc> <tables dir>: replace the text between the markers with a fresh block
  local out; out=$(mktemp "${TMPDIR:-/tmp}/jg-sm-index.XXXXXX") || return 1
  render_index "$2" > "$out.block"
  LC_ALL=C awk -v b="$BEGIN" -v e="$END" -v blk="$out.block" '
    $0 == b { print; while ((getline l < blk) > 0) print l; skip = 1; next }
    $0 == e { skip = 0 }
    !skip { print }' "$1" > "$out" && cat "$out" > "$1"
  rm -f "$out" "$out.block"
}

if [ "${1:-}" = "--write" ]; then splice "$DOC" "$TABLES"; exit $?; fi

T=$(jg_test_tmproot jg-machine-index); mkdir -p "$T/tables"
tab() { local IFS=$'\t'; printf '%s\n' "$*"; }
seed_tables() {  # <dir>: two machines and a baseline file, made here from nothing
  { tab machine doc "files in a folder | any" core/machines/bin/machine.py
    tab state draft initial "A draft." body; tab state closed terminal "Closed." -
    tab edge draft finish closed w:f c g t
    tab observer "cat \$1"; } > "$1/doc.tsv"
  { tab machine alpha "alpha records" bin/alpha.sh
    tab state a initial "A." -; tab state b normal "B." -; tab state c terminal "C." -
    tab edge a go b w:f c g t; tab edge b go c w:f c g t
    tab observer "cat \$1"; } > "$1/alpha.tsv"
  tab alpha "a go c" > "$1/known-baseline.tsv"
}

# The generator: golden output on seeded tables, in name order, escaped, baseline file skipped.
seed_tables "$T/tables"
# shellcheck disable=SC2016  # the backticks are literal Markdown
want=$(printf '%s\n' \
  "| Machine | Record it holds | Owner | States | Edges | Ask |" \
  "| --- | --- | --- | ---: | ---: | --- |" \
  '| `alpha` | `alpha records` | `bin/alpha.sh` | 3 | 2 | `bin/jg-machine.sh next alpha <id>` |' \
  '| `doc` | `files in a folder \| any` | `core/machines/bin/machine.py` | 2 | 1 | `bin/jg-machine.sh next doc <id>` |')
assert_equals "$want" "$(render_index "$T/tables")" "the index block matches golden output"
mkdir -p "$T/none"; assert_equals "No machine table is installed yet." "$(render_index "$T/none")" "an empty folder says so"
pass "the generator renders one row per machine, in name order"

# Regeneration is exact and leaves the hand-written text alone.
printf '%s\n' "intro line" "$BEGIN" "stale line" "$END" "outro line" > "$T/page.md"
splice "$T/page.md" "$T/tables"
assert_equals "$(printf '%s\n' "intro line" "$BEGIN" "$want" "$END" "outro line")" "$(cat "$T/page.md")" "splice replaces only the block"
cp "$T/page.md" "$T/page2.md"; splice "$T/page2.md" "$T/tables"
assert_equals "$(cat "$T/page.md")" "$(cat "$T/page2.md")" "splice twice equals once"
pass "regenerating twice equals once and keeps the text outside the markers"

# The committed page: it exists, carries the markers once, and its generated block equals a fresh regeneration.
[ -f "$DOC" ] || fail "docs/state-machines.md is missing"
assert_equals 1 "$(grep -cxF "$BEGIN" "$DOC")" "the page has one begin marker"
assert_equals 1 "$(grep -cxF "$END" "$DOC")" "the page has one end marker"
cp "$DOC" "$T/doc.copy"; splice "$T/doc.copy" "$TABLES"
if cmp -s "$DOC" "$T/doc.copy"; then pass "the committed index equals a fresh regeneration"
else echo "drift (report-only): docs/state-machines.md differs from core/machines/tables; run: bash tests/jg-machine-index.test.sh --write"; fi

# Every local link on the page resolves, and the page is classified for an audience.
links=$(grep -o '](\([^)#]*\)' "$DOC" | sed 's/^](//' | grep -v '^[a-z]*:' | sort -u)
[ -n "$links" ] || fail "the page links to nothing"
while IFS= read -r l; do [ -e "$(dirname "$DOC")/$l" ] || fail "the page links to $l, which does not exist"; done <<< "$links"
pass "every local link on the page resolves"
assert_contains "$(grep -A1 '"path": "docs/state-machines.md"' "$ROOT/docs/documentation-audiences.json")" '"audience"' "docs/state-machines.md is classified"
pass "the page has a documentation-audience row"

# The fix-method pointer: one line in the diagnostic-reasoning section names jg-machine and links to this page.
SK="$ROOT/.agents/skills/diagnostic-reasoning/SKILL.md"
sec=$(awk '/^## /{on = ($0 == "## Make the implicit state machine explicit")} on' "$SK")
[ -n "$sec" ] || fail "diagnostic-reasoning has no 'Make the implicit state machine explicit' section"
line=$(printf '%s\n' "$sec" | grep 'jg-machine' | grep 'state-machines.md')
assert_equals 1 "$(printf '%s\n' "$line" | grep -c .)" "exactly one pointer line names jg-machine and the index"
target=$(printf '%s' "$line" | grep -o '](\([^)#]*state-machines.md\)' | sed 's/^](//')
[ -e "$(dirname "$SK")/$target" ] || fail "the pointer line links to $target, which does not exist"
pass "the diagnostic-reasoning pointer resolves to the index"
