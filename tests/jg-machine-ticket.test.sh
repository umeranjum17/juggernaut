#!/usr/bin/env bash
# Behavior tests for the ticket statechart (core/machines/tables/{ticket,delivering,proving}.tsv) and its word map.
# The tables lint, the engine accepts a move out of a stage from every sub-state, each defect of the hierarchy is refused by
# name, the older words (this repository's nine tables, generated status logs, a generated shadow log) all have a target,
# and the 21 pull request records get their targets. `--write` regenerates the diagram in docs/ticket-statechart.md.
# shellcheck disable=SC2016,SC2013,SC2034
set -u
# shellcheck source=tests/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

JM="$ROOT/bin/jg-machine.sh" DOC="$ROOT/docs/ticket-statechart.md" TABLES="$ROOT/core/machines/tables"
T=$(jg_test_tmproot jg-machine-ticket); H=$T/home; mkdir -p "$H"/{state,data}
jm() { OUT=$(bash "$JM" "$@" 2>&1); RC=$?; }
tab() { local IFS=$'\t'; printf '%s\n' "$*"; }
diagram_block() { printf '<!-- diagram:begin (generated by tests/jg-machine-ticket.test.sh --write; do not edit) -->\n```mermaid\n%s\n```\n<!-- diagram:end -->\n' "$(bash "$JM" diagram ticket)"; }

if [ "${1:-}" = --write ]; then
  { sed '/<!-- diagram:begin/,$d' "$DOC"; diagram_block; sed '1,/<!-- diagram:end -->/d' "$DOC"; } > "$T/doc" && cp "$T/doc" "$DOC"; exit 0
fi


# The cases: one file each in tests/jg-machine-ticket.d/, run in name order in this shell. A new case is a new file, so two lanes never meet.
for c in "$(dirname "${BASH_SOURCE[0]}")/jg-machine-ticket.d"/*.sh; do
  # shellcheck source=/dev/null
  . "$c"
done
