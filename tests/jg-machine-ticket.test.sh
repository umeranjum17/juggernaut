#!/usr/bin/env bash
# Behavior tests for the ticket statechart (core/machines/tables/{ticket,delivering,proving}.tsv) and its word map.
# The tables lint, the engine accepts a move out of a stage from every sub-state, each defect of the hierarchy is refused by
# name, the older words (this repository's nine tables, generated status logs, a generated shadow log) all have a target,
# and the 21 pull request records get their targets. `--write` regenerates the diagram in docs/ticket-statechart.md.
# shellcheck disable=SC2016,SC2013
set -u
# shellcheck source=tests/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

JM="$ROOT/bin/jg-machine.sh" DOC="$ROOT/docs/ticket-statechart.md" TABLES="$ROOT/core/machines/tables"
T=$(jg_test_tmproot jg-machine-ticket); H=$T/home; mkdir -p "$H"/{state,data}
jm() { OUT=$(bash "$JM" "$@" 2>&1); RC=$?; }
tab() { local IFS=$'\t'; printf '%s\n' "$*"; }
diagram_block() { printf '<!-- diagram:begin (generated by tests/jg-machine-ticket.test.sh --write; do not edit) -->\n```mermaid\n%s\n```\n<!-- diagram:end -->\n' "$(bash "$JM" diagram ticket)"; }

if [ "${1:-}" = --write ]; then
  { sed '/<!-- diagram:begin/,$d' "$DOC"; diagram_block; sed '1,/<!-- diagram:end -->/d' "$DOC"; } > "$T/doc" && cp "$T/doc" "$DOC"; exit 0
fi

# 1. The three tables lint clean: 7 stages with 15 moves, delivering with 12 events and 7 sub-states, proving as the composite.
jm check ticket; expect_code 0 "$RC" "ticket lints"; assert_equals "ok ticket: 24 states, 15 edges" "$OUT" "ticket lint golden"
jm check delivering; assert_equals "ok delivering: 9 states, 12 edges" "$OUT" "delivering lint golden"
jm check proving; assert_equals "ok proving: 10 states, 14 edges" "$OUT" "proving lint golden"
assert_equals 7 "$(grep -c '^state	' "$TABLES/ticket.tsv")" "seven stages"
assert_equals 7 "$(grep -c '^state	.*	normal	\|^state	queued	' "$TABLES/delivering.tsv")" "seven sub-states of delivering besides its two ends"
assert_equals 15 "$(bash "$JM" events ticket | wc -l | tr -d ' ')" "fifteen moves"
assert_equals 12 "$(bash "$JM" events delivering | wc -l | tr -d ' ')" "twelve events inside delivering"
assert_equals "file approve start reclaim claim-done prove-fail prove-pass bypass answer new-head refuse release revert-released close drop" \
  "$(bash "$JM" events ticket | cut -f1 | tr '\n' ' ' | sed 's/ $//')" "the moves, by name"
jm coverage ticket; expect_code 0 "$RC" "every move names a test"
pass "the three tables lint and hold the counted moves"

# 2. A move out of a stage is legal from each of its sub-states; a stage that was left cannot be left again; closed is final.
for s in $(awk -F'\t' '$1=="state"{print $2}' "$TABLES/proving.tsv"); do
  jm edge-check ticket "proving.$s" building; expect_code 0 "$RC" "prove-fail from proving.$s"; assert_contains "$OUT" "prove-fail" "event named from proving.$s"
  jm edge-check ticket "proving.$s" delivering; expect_code 0 "$RC" "prove-pass from proving.$s"
done
for s in $(awk -F'\t' '$1=="state"{print $2}' "$TABLES/delivering.tsv"); do
  for to in building released; do jm edge-check ticket "delivering.$s" "$to"; expect_code 0 "$RC" "delivering.$s to $to"; done
  jm edge-check ticket "delivering.$s" proving; expect_code 0 "$RC" "new-head from delivering.$s"; assert_contains "$OUT" "proving.planned" "new-head lands on the first sub-state"
done
jm edge-check ticket intake proving; expect_code 1 "$RC" "intake cannot claim done"
jm edge-check ticket building delivering; expect_code 1 "$RC" "building cannot skip proving"
jm edge-check ticket closed intake; expect_code 1 "$RC" "closed is final"
jm edge-check delivering rebased queued; expect_code 1 "$RC" "a rebase cannot go back to the queue"
jm edge-check delivering resolving returned; expect_code 0 "$RC" "give-back from resolving"; jm edge-check delivering batched returned; expect_code 0 "$RC" "revert from the line"
for s in intake ready building proving.running delivering.gated released; do jm edge-check ticket "$s" closed; expect_code 0 "$RC" "drop from $s"; done
pass "every stage is left from each of its sub-states"

# 3. Each defect of the hierarchy is refused by name.
copy_tables() { rm -rf "$T/t"; mkdir -p "$T/t"; cp "$TABLES"/{ticket,delivering,proving}.tsv "$T/t/"; }
defect() {  # <name> <table> <expected text> <line to append>
  copy_tables; printf '%s\n' "$4" >> "$T/t/$2.tsv"
  OUT=$(JG_MACHINES_TABLES="$T/t" JG_MACHINES_ENUMS="$ROOT/core/machines" bash "$JM" check ticket 2>&1); RC=$?; expect_code 1 "$RC" "lint should refuse: $1"; assert_contains "$OUT" "$3" "lint should name: $1"
}
defect "an event with two targets from one sub-state" ticket "duplicate edge proving.waiting answer" "$(tab edge proving.waiting answer closed w:f - g t)"
defect "a way out of an end inside the inner table" proving "terminal state sealed has an exit edge" "$(tab edge sealed again planned w:f - g t)"
defect "an unreachable sub-state" delivering "unreachable state orphan" "$(tab state orphan normal 'Nobody gets here.' -)"
defect "a composite with no inner table" ticket "composite state limbo has no inner table" "$(tab state limbo composite 'A stage with nothing in it.' -)"
defect "a first event that leads away from the initial state" ticket "entry event again does not lead to the initial state" "$(tab edge '(none)' again ready w:f - g t)"
pass "the lint names each defect of the hierarchy"

# 4. The diagram in the docs is the one the tables draw.
assert_equals "$(diagram_block)" "$(sed -n '/<!-- diagram:begin/,/<!-- diagram:end -->/p' "$DOC")" "docs/ticket-statechart.md drifted: run bash tests/jg-machine-ticket.test.sh --write"
pass "the documented diagram is generated from the tables"

# 5. Replay: the words of the nine older tables, of status logs in three shapes and of a shadow log all have a target.
for v in working paused blocked needs-decision "done" resolved ready progress note failed; do
  printf '%s [at=1]: x\n2026-11-07T14:50:22Z %s: y\n%s: z\n' "$v" "$v" "$v"; done > "$H/state/lane-a.status"
tab 1794202567 task unknown "done" shadow > "$H/data/machine-shadow.log"; tab 1794202568 task landed "done" shadow >> "$H/data/machine-shadow.log"
tab 1794202569 task-inbox held-reported ring-counted shadow >> "$H/data/machine-shadow.log"
bash "$ROOT/core/machines/ticket-corpus.sh" --state "$H/state" --shadow "$H/data/machine-shadow.log" > "$T/corpus.tsv"
assert_equals 9 "$(awk -F'\t' '{print $1}' "$T/corpus.tsv" | sort -u | wc -l | tr -d ' ')" "the corpus holds the nine older tables"
assert_equals 44 "$(grep -c '^status-verb	' "$T/corpus.tsv")" "30 status lines in three shapes, as verbs, and the 14 states of the verb table"
jm replay ticket-words "$T/corpus.tsv"; expect_code 0 "$RC" "every word has a target"
assert_contains "$OUT" " 0 unmapped" "replay golden"
tab status-verb mystery >> "$T/corpus.tsv"
jm replay ticket-words "$T/corpus.tsv"; expect_code 1 "$RC" "a word without a target"; assert_contains "$OUT" "unmapped status-verb mystery" "replay names the word"
jm word ticket-words task rework; assert_equals "$(tab building worker red)" "$OUT" "rework is building, worker, red"
pass "every older word has a target"

# 6. The 21 records of the pull request style get their targets; a changed target is named.
jm records ticket-words "$ROOT/core/machines/corpus/pr-records.tsv"; expect_code 0 "$RC" "records"; assert_equals "ok ticket-words: 21 records, 0 differ" "$OUT" "records golden"
sed '3s/released/closed/' "$ROOT/core/machines/corpus/pr-records.tsv" > "$T/records.tsv"
jm records ticket-words "$T/records.tsv"; expect_code 1 "$RC" "a wrong target"; assert_contains "$OUT" "differs " "records name the record"
pass "the 21 pull request records get their targets"

# 7. A map that names a state the machine lacks, or a wait the enums lack, is refused.
mkdir -p "$T/maps"; cp "$ROOT/core/machines/maps/ticket-words.tsv" "$T/maps/"; tab word task bogus nowhere lead ok >> "$T/maps/ticket-words.tsv"
OUT=$(JG_MACHINES_MAPS="$T/maps" bash "$JM" word ticket-words task rework 2>&1); RC=$?; expect_code 1 "$RC" "a map with a bad target"
assert_contains "$OUT" "word task bogus: target nowhere is not a state of ticket" "the bad target is named"
pass "a bad map is refused"

# 8. The report-only observer reads the older readers and prints a state of the ticket.
mkdir -p "$H"/{bin,crew,rows}
printf '#!/usr/bin/env bash\nprintf "state: %%s · source: none · fixture\\n" "$(cat "$JG_HOME/crew/$1" 2>/dev/null || echo unknown)"\n' > "$H/bin/jg-crew-state.sh"
printf '#!/usr/bin/env bash\n[ -r "$JG_HOME/rows/$2" ] || exit 1\nprintf "task:\\n  id: %%s\\n  state: %%s\\n" "$2" "$(cat "$JG_HOME/rows/$2")"\n' > "$H/bin/jg-backlog.sh"
chmod +x "$H"/bin/*.sh; printf working > "$H/crew/w-1"; printf in_flight > "$H/rows/w-1"; printf 'kind=ship\n' > "$H/state/w-1.meta"
OUT=$(JG_HOME=$H bash "$JM" show ticket w-1 2>&1); RC=$?; expect_code 0 "$RC" "show ticket"; assert_contains "$OUT" "state	building" "a working task is building"
OUT=$(JG_HOME=$H bash "$JM" show delivering w-1 2>&1); RC=$?; expect_code 1 "$RC" "a building ticket is in no sub-state of delivering"
pass "the observer maps the older readers' words"
